function formDigest(form) {
  form = form || {};
  const val = k => { const v = form[k]; if (Array.isArray(v)) return v.join(', '); return v == null ? '' : String(v).trim(); };
  const lines = [];
  for (const f of recruit.REQUISITION_FIELDS) { const v = val(f.key); if (v) lines.push(`${f.label}: ${v}`); }
  if (form.traits) {
    let tr = form.traits; if (typeof tr === 'string') tr = tr.split(',').map(s => s.trim()).filter(Boolean);
    if (Array.isArray(tr) && tr.length) lines.push('Главные качества: ' + tr.map(k => recruit.traitLabel(k, 'ru')).join(', '));
  }
  return lines.join('\n');
}

const AD_ALLOWED = ['p', 'br', 'b', 'strong', 'i', 'em', 'u', 'ul', 'ol', 'li', 'h3', 'h4'];
export function sanitizeAdHtml(html) {
  let s = String(html || '');
  if (!/<(p|h3|ul|ol|li|b|strong|br)[\s>]/i.test(s)) {
    s = s.replace(/\*\*(.+?)\*\*/g, '<b>$1</b>').replace(/(^|\n)#{1,6}\s*(.+)/g, '$1<h3>$2</h3>')
      .split(/\n{2,}/).map(p => p.trim() ? '<p>' + p.replace(/\n/g, '<br>') + '</p>' : '').join('');
  }
  s = s.replace(/<script[\s\S]*?<\/script>/gi, '').replace(/<style[\s\S]*?<\/style>/gi, '')
    .replace(/ on\w+="[^"]*"/gi, '').replace(/ on\w+='[^']*'/gi, '');
  s = s.replace(/<\/?([a-z0-9]+)([^>]*)>/gi, (m, tag) => AD_ALLOWED.includes(tag.toLowerCase()) ? m.replace(/\s+(?:style|class|id)="[^"]*"/gi, '') : '');
  return s.trim();
}
function cleanComment(t) { return String(t || '').replace(/\[\[[A-Z]+\]\]/g, '').trim(); }
export function parseAdOutput(text) {
  const t = String(text || '').trim();
  const parts = t.split(/\[\[VARIANT\]\]/);
  const head = parts.shift() || '';
  const ci = head.indexOf('[[COMMENT]]');
  const comment = cleanComment(ci >= 0 ? head.slice(ci + '[[COMMENT]]'.length) : head);
  const variants = parts.map(p => {
    const nl = p.indexOf('\n');
    const title = (nl >= 0 ? p.slice(0, nl) : p).trim().replace(/[«»"]/g, '').slice(0, 120);
    const html = sanitizeAdHtml((nl >= 0 ? p.slice(nl + 1) : '').trim());
    return { title, html };
  }).filter(v => v.html);
  if (!variants.length) return { comment: '', variants: [{ title: '', html: sanitizeAdHtml(t.replace(/\[\[[A-Z]+\]\]/g, '')) }] };
  return { comment, variants };
}
async function callClaude(env, system, user, maxTokens) {
  const key = env.ANTHROPIC_API_KEY;
  if (!key) throw new Error('ANTHROPIC_API_KEY не задан');
  const r = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: { 'x-api-key': key, 'anthropic-version': '2023-06-01', 'content-type': 'application/json', 'anthropic-beta': 'prompt-caching-2024-07-31' },
    body: JSON.stringify({ model: MODEL, max_tokens: maxTokens || 3200, system, messages: [{ role: 'user', content: user }] }),
  });
  const d = await r.json();
  if (!r.ok) throw new Error('Anthropic: ' + ((d.error && d.error.message) || r.status));
  return (d.content || []).filter(b => b.type === 'text').map(b => b.text).join('').trim();
}

export async function generateAd(env, ctx) {
  const lang = ['ru', 'pl', 'en'].includes(ctx.lang) ? ctx.lang : 'ru';
  const form = Object.assign({}, ctx.form || {});
  if (!form.position && ctx.vacancyName) form.position = ctx.vacancyName;
  const digest = formDigest(form) || ('Должность: ' + (form.position || ctx.vacancyName || '—'));
  const targetHint = ctx.target === 'executor' ? 'Подсказка пользователя: ориентир — хороший дуер (исполнитель), если должность это допускает.'
    : ctx.target === 'performer' ? 'Подсказка пользователя: ориентир — виннер (результатник).' : '';
  const system = [
    { type: 'text', text: KB, cache_control: { type: 'ephemeral', ttl: '1h' } },
    { type: 'text', text: promptFor(lang) },
  ];
  const user = `ЗАЯВКА НА НАЙМ:
${digest}
${ctx.company ? '\nКомпания: ' + ctx.company : ''}
${targetHint ? '\n' + targetHint : ''}

Составь объявление(я) строго по методологии и формату из инструкции. Используй КОНКРЕТИКУ из заявки (продукт, обязанности, сложности, условия), не общие штампы.`;
  const raw = await callClaude(env, system, user, 3600);
  const parsed = parseAdOutput(raw);
  return { comment: parsed.comment, variants: parsed.variants, raw };
}
