// Нормализация телефона до «национального хвоста» (последние 9 цифр).
function phoneKey(s) {
  const d = String(s || '').replace(/\D/g, '').replace(/^00/, '');
  return d.slice(-9);
}

// В E.164 для звонка: 9 цифр без кода → польский +48; 00XX → +XX; иначе + и цифры.
function toE164(s) {
  const raw = String(s || '').trim();
  let d = raw.replace(/\D/g, '');
  if (d.startsWith('00')) d = d.slice(2);
  if (d.length === 9) return '+48' + d;              // локальный польский без кода
  if (d.length === 11 && d.startsWith('48')) return '+' + d;
  if (raw.startsWith('+')) return '+' + d;
  return '+' + d;
}

