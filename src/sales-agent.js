// Итог звонка → обновление полей лида (по structuredData/summary).
function applyCallResult(lead, { summary, sd, transcript }) {
  // «прочерк»/«нет»/«brak»/«n/a» и т.п. — это «пусто», а не значение
  const EMPTYISH = /^[—\-–\s.]*$|^(прочерк|нет|не\s.*|пусто|none|null|n\/a|brak|nie|no)$/i;
  const pick = (v) => { const s = String(v == null ? '' : v).trim(); return (s && !EMPTYISH.test(s)) ? s : ''; };
  const fromSummary = (rx) => ((String(summary || '').match(rx) || [])[1] || '');
  const email = pick(sd && (sd.email || sd.client_email)) || pick(fromSummary(/EMAIL:\s*([^\s\n]+@[^\s\n]+)/i));
  if (email && isValidEmail(email)) lead.email = email.toLowerCase();
  const nm = pick(sd && (sd.person_name || sd.client_name)); if (nm && !lead.name) lead.name = nm;
  const comp = pick(sd && sd.company); if (comp) lead.company = comp;
  const interest = pick(sd && sd.interest); if (interest) lead.interest = interest;
  const cb = pick(sd && sd.callback_when) || pick(fromSummary(/ПЕРЕЗВОН:\s*([^\n]+)/i));
  if (cb) lead.callbackWhen = cb;
  const out = (pick(sd && sd.outcome) || pick(fromSummary(/СТАТУС:\s*(\w+)/i))).toLowerCase();
  const answered = String(transcript || '').trim().length >= 20;
  if (sd && sd.do_not_call === true) lead.status = 'do_not_call';
  else if (out === 'refused') lead.status = 'refused';
  else if (out === 'registered') lead.status = 'registered';
  else if (out === 'callback' || cb) lead.status = 'callback';
  else if (out === 'voicemail' || !answered) lead.status = lead.status === 'new' ? 'no_answer' : (lead.status || 'no_answer');
  else if (lead.status !== 'converted') lead.status = 'talked';
  if (sd && pick(sd.refusal_reason)) lead.refusalReason = pick(sd.refusal_reason);
  return lead;
}

// Полная история прошлых разговоров — для повторных звонков (ИИ «помнит всё»).
function historyBlock(lead) {
  const log = (Array.isArray(lead && lead.aiCallLog) ? lead.aiCallLog : []).filter(e => e.summary || (e.transcript && e.transcript.length > 60));
  if (!log.length) return '';
  const rows = log.slice(-6).map(e => {
    const when = String(e.createdAt || '').slice(0, 16).replace('T', ' ');
    const dir = e.dir === 'in' ? 'он звонил нам' : 'мы звонили ему';
    const sum = String(e.summary || '').replace(/\s+/g, ' ').trim() || ('Фрагмент: ' + String(e.transcript || '').replace(/\s+/g, ' ').slice(0, 250));
    return `• [${when}, ${dir}] ${sum.slice(0, 500)}`;
  });
  return 'ИСТОРИЯ ВСЕХ ПРОШЛЫХ РАЗГОВОРОВ С ЭТИМ ЧЕЛОВЕКОМ (ты всё это ПОМНИШЬ — не переспрашивай то, что уже обсуждали, ссылайся на прошлые договорённости естественно):\n' + rows.join('\n');
}

