// Текст пакетов из настроек портала → строка для базы знаний.
function plansText(plans, currency) {
  const cur = { eur: 'евро', pln: 'злотых', usd: 'долларов' }[String(currency || 'eur').toLowerCase()] || String(currency || 'евро');
  const rows = (Array.isArray(plans) ? plans : []).filter(p => p && p.active !== false)
    .sort((a, b) => (a.order || 0) - (b.order || 0))
    .map(p => `  • ${p.qty} тестов — ${p.price} ${cur}${p.save ? ` (выгода ${p.save}%)` : ''}`);
  return rows.length ? '- ПАКЕТЫ ТЕСТОВ (чем больше — тем дешевле за штуку):\n' + rows.join('\n') : '- Пакеты тестов: 25, 60, 160 и 300 проверок; чем больше пакет, тем ниже цена за тест.';
}

